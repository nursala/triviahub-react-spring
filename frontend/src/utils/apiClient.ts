/**
 * Centralized frontend API client for the Spring Boot backend.
 * Keeps request construction and response-shape assumptions in one module so
 * pages and components can stay focused on UI state.
 */

const API_BASE_URL = import.meta.env.VITE_API_BASE_URL || "/api";

export interface Quiz {
  id: string;
  title: string;
  category: string;
  description: string;
  questionCount?: number;
}

export interface Question {
  id: string;
  quizId: string;
  text: string;
  options: string[];
  correctIndex: number;
  hint: string;
  difficulty: string;
}

/**
 * Payload used when sending question data back to the backend.
 * The identifier stays outside this type because updates carry it in the URL.
 */
export type QuestionInput = Omit<Question, "id">;

export interface GameResult {
  id: string;
  quizId: string;
  quizTitle?: string;
  playerName: string;
  score: number;
  correctAnswers?: number;
  totalQuestions?: number;
  durationSeconds?: number;
  hintsUsed?: number;
  playedAt?: string;
}

export interface APIError {
  error: string;
  status: number;
}

/**
 * Fetches all quizzes from the backend.
 * @param signal Optional AbortSignal for request cancellation
 * @returns Promise resolving to an array of quizzes
 * @throws APIError if the request fails
 */
export async function fetchAllQuizzes(signal?: AbortSignal): Promise<Quiz[]> {
  const response = await fetch(`${API_BASE_URL}/quizzes`, { signal });
  if (!response.ok) {
    const error = await response.json();
    throw {
      error: error.error || "Failed to fetch quizzes",
      status: response.status,
    };
  }
  return response.json();
}

/**
 * Fetches a specific quiz by ID from the backend.
 * @param quizId The ID of the quiz to fetch
 * @param signal Optional AbortSignal for request cancellation
 * @returns Promise resolving to the quiz object
 * @throws APIError if the quiz is not found or request fails
 */
export async function fetchQuizById(quizId: string, signal?: AbortSignal): Promise<Quiz> {
  const response = await fetch(`${API_BASE_URL}/quizzes/${quizId}`, { signal });
  if (!response.ok) {
    const error = await response.json();
    throw {
      error: error.error || "Quiz not found",
      status: response.status,
    };
  }
  return response.json();
}

/**
 * Creates a new quiz on the backend.
 * @param quiz The quiz object to create (id auto-generated by backend)
 * @param signal Optional AbortSignal for request cancellation
 * @returns Promise resolving to the created quiz with generated ID
 * @throws APIError if duplicate title or other validation error occurs
 */
export async function createQuiz(quiz: Omit<Quiz, "id">, signal?: AbortSignal): Promise<Quiz> {
  const response = await fetch(`${API_BASE_URL}/quizzes`, {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify(quiz),
    signal,
  });
  if (!response.ok) {
    const error = await response.json();
    throw {
      error: error.error || "Failed to create quiz",
      status: response.status,
    };
  }
  return response.json();
}

